/** 图标的 SVG 源码。给已经在用 `h('span', { html })` 的老写法。 */
export function iconSvg(name, className = '') {
  const shape = ICON_SHAPES[name];
  if (!shape) return '';
  const cls = className ? `icon ${className}` : 'icon';
  return `<svg viewBox="0 0 24 24" class="${cls}" aria-hidden="true">${shape}</svg>`;
}

/**
 * 图标节点。
 *
 * 外面套一层 span 而不是直接给 svg 设 innerHTML —— SVGElement.innerHTML
 * 在旧一些的 Safari 上不可用，而这个应用主要跑在 iOS 上。
 * span 走 `display: contents`，不进布局。
 */
export function icon(name, className = '') {
  return h('span.icon-slot', { html: iconSvg(name, className), 'aria-hidden': 'true' });
}

/**
 * 就地换掉一个元素里的图标。
 *
 * 勾选类控件会在「＋ / ✓」之间来回切，原先是 `el.textContent = '✓'` 一行搞定；
 * 换成描边图标之后不能再写 textContent，但也不该为了换个图标整行重绘 ——
 * 健身页刻意只改那一行的 DOM（见 training.js 里勾选那段注释）。
 */
export function setIcon(el, name, className = '') {
  if (!el) return el;
  el.replaceChildren(icon(name, className));
  return el;
}

/** 纯装饰的图标不该被读屏念出来，但按钮本身必须有名字。 */
export function iconButton(name, { className = '', label, onclick, ...rest } = {}) {
  return h(`button.icon-btn${className ? `.${className.split(' ').join('.')}` : ''}`, {
    type: 'button', 'aria-label': label, title: label, onclick, ...rest,
  }, icon(name));
}
