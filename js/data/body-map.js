/** 把左半边的路径镜像到右半边：x → 100 − x */
export function mirrorPath(d) {
  return d.replace(/(-?\d*\.?\d+)\s*,\s*(-?\d*\.?\d+)/g, (_, x, y) => `${100 - Number(x)},${y}`);
}

